//! The generated hub notes, rewritten from the folders (brain-hubs.mjs, ported in Stage 6). They
//! keep every note within two hops of 00-MOC-Root (records within three), and they are written from
//! the folder contents every time, so they cannot drift. Never edit one by hand.
//!
//!   knowledge hubs
use crate::config::Config;
use crate::state::{self, OPS, PLANS, SESSIONS};
use crate::{Fault, emit};
use std::fs;
use std::path::Path;

fn names(dir: &Path) -> Vec<String> {
    fs::read_dir(dir)
        .map(|rd| {
            rd.flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .collect()
        })
        .unwrap_or_default()
}

/// The notes in a folder, hubs excluded, in the folder's own order.
fn md(dir: &Path) -> Vec<String> {
    names(dir)
        .into_iter()
        .filter(|f| f.ends_with(".md") && !f.starts_with("00-MOC"))
        .collect()
}

fn digits(s: &str, n: usize) -> bool {
    s.len() == n && s.bytes().all(|b| b.is_ascii_digit())
}

fn stem(f: &str) -> &str {
    f.strip_suffix(".md").unwrap_or(f)
}

/// A frontmatter-style `key: value` line's first word, from anywhere in the text.
fn field(text: &str, key: &str) -> Option<String> {
    text.lines().find_map(|l| {
        let v = l.strip_prefix(key)?.strip_prefix(':')?;
        v.split_whitespace().next().map(str::to_string)
    })
}

/// A hub keeps the `created:` it was first written with; a new vault's hubs start today (UTC).
fn created_of(file: &Path, today: &str) -> String {
    field(&state::read(file), "created").unwrap_or_else(|| today.to_string())
}

/// `updated` follows `created`: hubs are rewritten on both boots and some merge by union.
fn fm(tags: &str, file: &Path, today: &str) -> Vec<String> {
    let c = created_of(file, today);
    vec![
        "---".into(),
        "type: moc".into(),
        "project: knowledge".into(),
        format!("tags: [moc, {tags}, generated]"),
        format!("created: {c}"),
        format!("updated: {c}"),
        "status: active".into(),
        "---".into(),
        String::new(),
    ]
}

/// A note's H1, or its file name, with `|` and `]` made safe for a link.
fn title(p: &Path) -> String {
    let text = state::read(p);
    text.lines()
        .find_map(|l| l.strip_prefix("# ").filter(|t| !t.is_empty()))
        .map_or_else(
            || stem(&p.file_name().unwrap_or_default().to_string_lossy()).to_string(),
            str::to_string,
        )
        .replace(['|', ']'], "-")
}

fn put(file: &Path, lines: &[String]) -> Result<(), Fault> {
    fs::write(file, format!("{}\n", lines.join("\n"))).map_err(|e| Fault::io(file, e))
}

fn sessions(cfg: &Config, today: &str) -> Result<(), Fault> {
    let root = cfg.vault.join(SESSIONS);
    let hub = root.join("00-MOC-Sessions.md");
    let mut out = fm("sessions", &hub, today);
    out.extend([
        "# Sessions".into(),
        String::new(),
        format!(
            "Daily logs, {:02}:00 local-time rollover. Generated by `brain-hubs`.",
            cfg.rollover
        ),
    ]);
    let mut years: Vec<String> = names(&root).into_iter().filter(|d| digits(d, 4)).collect();
    years.sort();
    for y in years.iter().rev() {
        let mut months: Vec<String> = names(&root.join(y))
            .into_iter()
            .filter(|d| digits(d, 2))
            .collect();
        months.sort();
        for m in months.iter().rev() {
            let mut days = md(&root.join(y).join(m));
            days.sort();
            if !days.is_empty() {
                out.extend([String::new(), format!("## {y}-{m}"), String::new()]);
                out.extend(days.iter().rev().map(|f| format!("- [[{}]]", stem(f))));
            }
        }
    }
    put(&hub, &out)
}

fn plans(cfg: &Config, today: &str) -> Result<(), Fault> {
    let root = cfg.vault.join(PLANS);
    let hub = root.join("00-MOC-Plans.md");
    let mut out = fm("plans", &hub, today);
    out.extend(["# Plans".into(), String::new(), "Cross-repo plans, one folder each: `<slug>/<slug>.md` is the plan. Generated by `brain-hubs`.".into()]);
    let mut dirs: Vec<String> = names(&root)
        .into_iter()
        .filter(|d| root.join(d).is_dir())
        .collect();
    dirs.sort();
    for d in dirs.iter().rev() {
        let main = root.join(d).join(format!("{d}.md"));
        if !main.exists() {
            continue;
        }
        let status = field(&state::read(&main), "status").unwrap_or_else(|| "?".into());
        out.extend([
            String::new(),
            format!("## {}", title(&main)),
            String::new(),
            format!("- [[{d}]] — `{status}`"),
        ]);
        let mut rest: Vec<String> = md(&root.join(d))
            .into_iter()
            .filter(|f| *f != format!("{d}.md"))
            .collect();
        rest.sort();
        out.extend(rest.iter().map(|f| format!("- [[{}]]", stem(f))));
        for sub in ["stages", "evidence"] {
            let mut files = md(&root.join(d).join(sub));
            files.sort();
            out.extend(files.iter().map(|f| format!("  - {sub}: [[{}]]", stem(f))));
        }
    }
    put(&hub, &out)
}

fn ops(cfg: &Config, today: &str) -> Result<(), Fault> {
    let root = cfg.vault.join(OPS);
    let hub = root.join("00-MOC-Ops.md");
    let mut out = fm("ops", &hub, today);
    out.extend([
        "# Ops".into(),
        String::new(),
        "Machine-written operational records. Generated by `brain-hubs`.".into(),
    ]);
    for (sub, label) in [
        ("Commits", "Commits — one note per commit, indexed by month"),
        ("Usage", "Usage — tokens, models, cost"),
        ("Health", "Health — the daily vault sweep"),
    ] {
        let mut files = md(&root.join(sub));
        files.sort();
        if !files.is_empty() {
            out.extend([String::new(), format!("## {label}"), String::new()]);
            out.extend(files.iter().rev().map(|f| format!("- [[{}]]", stem(f))));
        }
    }
    let loose = md(&root);
    if !loose.is_empty() {
        out.extend([String::new(), "## Other".into(), String::new()]);
        out.extend(loose.iter().map(|f| format!("- [[{}]]", stem(f))));
    }
    put(&hub, &out)
}

pub fn write(cfg: &Config) -> Result<(), Fault> {
    let today = state::iso(state::now_ms())[..10].to_string();
    sessions(cfg, &today)?;
    plans(cfg, &today)?;
    ops(cfg, &today)
}

pub fn run(_: &[String]) -> Result<u8, Fault> {
    let cfg = crate::config::load()?;
    match write(&cfg) {
        Ok(()) => Ok(0),
        Err(e) => {
            emit("");
            eprintln!("brain-hubs: {e}");
            Ok(1)
        }
    }
}
